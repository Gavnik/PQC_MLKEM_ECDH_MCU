/* ---- memtopo (diagnostic image only, CONFIG_PQC_FETCHTEST=y; m4 / PSoC 62; 2026-11-11) ----
 * Question: why is CM4 code in SRAM slower than in flash when the data is in SRAM?
 * Facts from the documentation:
 *   - PSoC 6 SRAM (0x08000000) lies in the Arm Code region (datasheet 3.1.9), so the CM4 fetches it
 *     over ICode and reads/writes it over DCode (Cortex-M4 TRM 2.3.1); "All fetches are word-wide".
 *   - The CM4 8 KB cache sits in the flash controller and "only captures FLASH macro main array data"
 *     (registers TRM, FLASHC_FLASH_CMD), so code in SRAM is never cached.
 *   - SRAM wait states: CPUSS_RAMx_CTL0.FAST_WS (CM4 side) and SLOW_WS, in clk_hf cycles.
 * One kernel set, timed with code in {flash, SRAM0, SRAM1, SRAM2} x data in {flash, SRAM0, SRAM1, SRAM2}.
 * Kernels (66 instructions per loop: 64 + subs + bne.w):
 *   alu16 = 64 x adds (2 B)   alu32 = 64 x add.w (4 B)   -> fetch only
 *   ld16  = 64 x ldr  (2 B)   ld32  = 64 x ldr.w (4 B)   -> fetch + one load per instruction
 *   st16  = 64 x str  (2 B)   st32  = 64 x str.w (4 B)   -> fetch + one store per instruction
 * The 16-bit and 32-bit forms do the same data work but need 1/2 and 1 fetch word per instruction,
 * so each candidate cause predicts different numbers (see scripts/memtopo_check.py):
 *   H1 slow SRAM (wait states)              : alu from SRAM > 1.0
 *   H2 ICode+DCode merged for every target  : code flash + data SRAM slow
 *   H3 conflict inside one SRAM controller  : code SRAMa + data SRAMb (a != b) fast
 *   H4 one shared CM4 path to all SRAM      : code SRAMa + data SRAMb slow, ~1.5 (16-bit) and ~2.0 (32-bit);
 *      (flash has its own)                    code flash + data flash slow the same way; mixed fast
 * The MPU stays ON with Zephyr's real attributes; while a kernel runs (interrupts locked) one free MPU
 * region temporarily marks SRAM executable with the same type as Zephyr's SRAM region (TEX=1 C=1 B=1).
 * The test windows lie above the image's RAM; their old contents are saved and restored. */
__asm__(
"  .section .text.mt_kernels,\"ax\",%progbits\n"
"  .syntax unified\n"
"  .thumb\n"
"  .balign 4\n"
"  .global mt_k_alu16\n  .type mt_k_alu16,%function\n  .thumb_func\n"
"mt_k_alu16:\n"
"1:\n  .rept 64\n  adds r2, r2, r3\n  .endr\n  subs r0, r0, #1\n  bne.w 1b\n  bx lr\n"
"  .balign 4\n"
"  .global mt_k_alu32\n  .type mt_k_alu32,%function\n  .thumb_func\n"
"mt_k_alu32:\n"
"1:\n  .rept 64\n  add.w r2, r2, r3\n  .endr\n  subs r0, r0, #1\n  bne.w 1b\n  bx lr\n"
"  .balign 4\n"
"  .global mt_k_ld16\n  .type mt_k_ld16,%function\n  .thumb_func\n"
"mt_k_ld16:\n"
"1:\n  .rept 64\n  ldr r2, [r1]\n  .endr\n  subs r0, r0, #1\n  bne.w 1b\n  bx lr\n"
"  .balign 4\n"
"  .global mt_k_ld32\n  .type mt_k_ld32,%function\n  .thumb_func\n"
"mt_k_ld32:\n"
"1:\n  .rept 64\n  ldr.w r2, [r1]\n  .endr\n  subs r0, r0, #1\n  bne.w 1b\n  bx lr\n"
"  .balign 4\n"
"  .global mt_k_st16\n  .type mt_k_st16,%function\n  .thumb_func\n"
"mt_k_st16:\n"
"1:\n  .rept 64\n  str r2, [r1]\n  .endr\n  subs r0, r0, #1\n  bne.w 1b\n  bx lr\n"
"  .balign 4\n"
"  .global mt_k_st32\n  .type mt_k_st32,%function\n  .thumb_func\n"
"mt_k_st32:\n"
"1:\n  .rept 64\n  str.w r2, [r1]\n  .endr\n  subs r0, r0, #1\n  bne.w 1b\n  bx lr\n"
"  .balign 4\n"
"  .global mt_k_end\n"
"mt_k_end:\n"
"  .previous\n");

extern const char mt_k_alu16[], mt_k_alu32[], mt_k_ld16[], mt_k_ld32[], mt_k_st16[], mt_k_st32[], mt_k_end[];

#define MT_NK      6
#define MT_SLOT    0x200u                 /* bytes per copied kernel (largest kernel is 264 B) */
#define MT_CODE_SZ (MT_NK * MT_SLOT)
#define MT_DATA_SZ 0x100u
#define MT_NWIN    3
static const char *const mt_kname[MT_NK] = { "alu16", "alu32", "ld16", "ld32", "st16", "st32" };
/* PSoC 62 (CY8C62xA): SRAM0 512 KB, SRAM1 256 KB, SRAM2 256 KB from 0x08000000 (datasheet 3.1.7).
 * The bank boundaries are not in the address map; the st16 rows check them (same bank is slower). */
static const char *const mt_wname[MT_NWIN] = { "SRAM0", "SRAM1", "SRAM2" };
static const uintptr_t mt_wcode[MT_NWIN] = { 0x08070000u, 0x08090000u, 0x080D0000u };
static const uintptr_t mt_wdata[MT_NWIN] = { 0x08078000u, 0x08098000u, 0x080D8000u };
static uint8_t mt_save_code[MT_NWIN][MT_CODE_SZ];
static uint8_t mt_save_data[MT_NWIN][MT_DATA_SZ];

static uintptr_t mt_src(int k)
{
    const char *s[MT_NK + 1] = { mt_k_alu16, mt_k_alu32, mt_k_ld16, mt_k_ld32, mt_k_st16, mt_k_st32, mt_k_end };
    return (uintptr_t)s[k] & ~1u;
}

static int mt_free_region(void)                 /* highest-numbered disabled MPU region (wins on overlap) */
{
    int n = (int)((MPU_TYPE_REG >> 8) & 0xFFu);
    for (int i = n - 1; i >= 0; i--) {
        MPU_RNR_REG = (uint32_t)i;
        if (!(MPU_RASR_REG & 1u)) return i;
    }
    return -1;
}

/* Time one kernel: interrupts locked, SRAM made executable only for the duration, min of 7 runs. */
/* 1 if an enabled region numbered above 'reg' overlaps a test window (it would override ours). */
static int mt_shadowed(int reg)
{
    int n = (int)((MPU_TYPE_REG >> 8) & 0xFFu);
    for (int i = reg + 1; i < n; i++) {
        MPU_RNR_REG = (uint32_t)i;
        uint32_t rasr = MPU_RASR_REG;
        if (!(rasr & 1u)) continue;
        uintptr_t b = MPU_RBAR_REG & 0xFFFFFFE0u;
        uintptr_t e = b + (1u << (((rasr >> 1) & 0x1Fu) + 1u));
        for (int w = 0; w < MT_NWIN; w++) {
            if (mt_wcode[w] < e && mt_wcode[w] + MT_CODE_SZ > b) return 1;
            if (mt_wdata[w] < e && mt_wdata[w] + MT_DATA_SZ > b) return 1;
        }
    }
    return 0;
}

static uint32_t mt_time(uintptr_t fn_addr, volatile uint32_t *buf, int reg)
{
    void (*fn)(uint32_t, volatile uint32_t *) = (void (*)(uint32_t, volatile uint32_t *))(fn_addr | 1u);
    uint32_t mn = 0xFFFFFFFFu;
    unsigned int key = irq_lock();
    MPU_RNR_REG = (uint32_t)reg;
    uint32_t old_rbar = MPU_RBAR_REG, old_rasr = MPU_RASR_REG;
    __DMB();
    MPU_RBAR_REG = 0x08000000u;
    /* XN=0, AP=1 (priv RW), TEX=1 S=0 C=1 B=1 (= Zephyr's SRAM region), SIZE=2^20 (1 MB), enable */
    MPU_RASR_REG = (1u << 24) | (1u << 19) | (1u << 17) | (1u << 16) | ((20u - 1u) << 1) | 1u;
    __DSB(); __ISB();
    fn(2u, buf);                                  /* warm up */
    for (int i = 0; i < 7; i++) {
        uint32_t t0 = FT_DWT_CYCCNT;
        fn(1000u, buf);
        uint32_t d = FT_DWT_CYCCNT - t0;
        if (d < mn) mn = d;
    }
    __DMB();
    MPU_RNR_REG = (uint32_t)reg;
    MPU_RASR_REG = 0u;
    MPU_RBAR_REG = old_rbar;
    MPU_RASR_REG = old_rasr;
    __DSB(); __ISB();
    irq_unlock(key);
    return mn;
}

static void mt_emit(int k, const char *code, const char *data, uintptr_t fn, uintptr_t buf, uint32_t cyc)
{
    MCU_EMIT("MEMTOPO kernel=%s code=%s data=%s fn=0x%08x buf=0x%08x instr=66000 cyc=%u cpi_x1000=%u",
             mt_kname[k], code, data, (unsigned)fn, (unsigned)buf, (unsigned)cyc,
             (unsigned)((uint64_t)cyc * 1000u / 66000u));
}

static void memtopo_test(void)
{
    FT_DEMCR |= (1u << 24);
    FT_DWT_CYCCNT = 0;
    FT_DWT_CTRL |= 1u;

    /* 1. Configuration that could make SRAM slow without any error (all read back from the chip). */
    uint32_t cm4clk = REG32(0x40200008u), cm0clk = REG32(0x40201008u);
    MCU_EMIT("MEMTOPO cfg cpu_hz(config)=%u CM4_CLOCK_CTL=0x%08x FAST_INT_DIV=%u CM0_CLOCK_CTL=0x%08x SLOW_INT_DIV=%u PERI_INT_DIV=%u",
             (unsigned)CONFIG_SYS_CLOCK_HW_CYCLES_PER_SEC, (unsigned)cm4clk, (unsigned)((cm4clk >> 8) & 0xFFu),
             (unsigned)cm0clk, (unsigned)((cm0clk >> 8) & 0xFFu), (unsigned)((cm0clk >> 24) & 0xFFu));
    static const uint32_t wsreg[4] = { 0x40201300u, 0x40201380u, 0x402013A0u, 0x402013C4u };
    static const char *const wsname[4] = { "RAM0_CTL0", "RAM1_CTL0", "RAM2_CTL0", "ROM_CTL" };
    for (int i = 0; i < 4; i++) {
        uint32_t v = REG32(wsreg[i]);
        MCU_EMIT("MEMTOPO cfg %s=0x%08x FAST_WS=%u SLOW_WS=%u", wsname[i], (unsigned)v,
                 (unsigned)((v >> 8) & 0x3u), (unsigned)(v & 0x3u));
    }
    uint32_t fctl = REG32(0x40240000u), ca4 = REG32(0x40240480u);
    MCU_EMIT("MEMTOPO cfg FLASH_CTL=0x%08x MAIN_WS=%u CM4_CA_CTL0=0x%08x CA_EN=%u PREF_EN=%u",
             (unsigned)fctl, (unsigned)(fctl & 0xFu), (unsigned)ca4, (unsigned)(ca4 >> 31), (unsigned)((ca4 >> 30) & 1u));
    dump_mpu();

    /* 2. Safety: the windows must lie above everything the image uses. */
    uintptr_t re = (uintptr_t)_image_ram_end;
    MCU_EMIT("MEMTOPO image RAM ends at 0x%08x; windows code=0x%08x/0x%08x/0x%08x data=0x%08x/0x%08x/0x%08x",
             (unsigned)re, (unsigned)mt_wcode[0], (unsigned)mt_wcode[1], (unsigned)mt_wcode[2],
             (unsigned)mt_wdata[0], (unsigned)mt_wdata[1], (unsigned)mt_wdata[2]);
    if (!re || re > mt_wcode[0]) {
        MCU_EMIT("MEMTOPO refused -- the image uses RAM above 0x%08x (run it on the flash image build-m4-fetch)",
                 (unsigned)mt_wcode[0]);
        MCU_EMIT("MEMTOPO done");
        return;
    }
    int reg = mt_free_region();
    if (reg < 0 || mt_shadowed(reg)) {
        MCU_EMIT("MEMTOPO refused -- no free MPU region above the ones covering the windows");
        MCU_EMIT("MEMTOPO done");
        return;
    }
    for (int k = 0; k < MT_NK; k++) {
        if (mt_src(k + 1) - mt_src(k) > MT_SLOT) {
            MCU_EMIT("MEMTOPO refused -- kernel %s is %u B > slot", mt_kname[k], (unsigned)(mt_src(k + 1) - mt_src(k)));
            MCU_EMIT("MEMTOPO done");
            return;
        }
    }
    MCU_EMIT("MEMTOPO using MPU region %d; kernel sizes alu16=%u alu32=%u ld16=%u ld32=%u st16=%u st32=%u B", reg,
             (unsigned)(mt_src(1) - mt_src(0)), (unsigned)(mt_src(2) - mt_src(1)), (unsigned)(mt_src(3) - mt_src(2)),
             (unsigned)(mt_src(4) - mt_src(3)), (unsigned)(mt_src(5) - mt_src(4)), (unsigned)(mt_src(6) - mt_src(5)));

    /* 3. Save the windows, copy the kernels into each SRAM bank. */
    for (int w = 0; w < MT_NWIN; w++) {
        memcpy(mt_save_code[w], (const void *)mt_wcode[w], MT_CODE_SZ);
        memcpy(mt_save_data[w], (const void *)mt_wdata[w], MT_DATA_SZ);
        for (int k = 0; k < MT_NK; k++)
            memcpy((void *)(mt_wcode[w] + (uintptr_t)k * MT_SLOT), (const void *)mt_src(k), mt_src(k + 1) - mt_src(k));
        memset((void *)mt_wdata[w], 0, MT_DATA_SZ);
    }
    __DSB(); __ISB();

    /* 4. The matrix. code: 0 = flash, 1..3 = SRAM0..2; data: 0 = flash (loads only), 1..3 = SRAM0..2. */
    for (int k = 0; k < MT_NK; k++) {
        int is_alu = (k < 2), is_st = (k >= 4);
        for (int c = 0; c <= MT_NWIN; c++) {
            uintptr_t fn = c ? mt_wcode[c - 1] + (uintptr_t)k * MT_SLOT : mt_src(k);
            const char *cn = c ? mt_wname[c - 1] : "flash";
            if (is_alu) {
                mt_emit(k, cn, "none", fn, 0u, mt_time(fn, (volatile uint32_t *)mt_wdata[0], reg));
                continue;
            }
            for (int d = is_st ? 1 : 0; d <= MT_NWIN; d++) {
                uintptr_t b = d ? mt_wdata[d - 1] : (uintptr_t)ft_fbuf;
                mt_emit(k, cn, d ? mt_wname[d - 1] : "flash", fn, b, mt_time(fn, (volatile uint32_t *)b, reg));
            }
        }
    }

    /* 5. Restore the windows. */
    for (int w = 0; w < MT_NWIN; w++) {
        memcpy((void *)mt_wcode[w], mt_save_code[w], MT_CODE_SZ);
        memcpy((void *)mt_wdata[w], mt_save_data[w], MT_DATA_SZ);
    }
    __DSB(); __ISB();
    MCU_EMIT("MEMTOPO done");
}
