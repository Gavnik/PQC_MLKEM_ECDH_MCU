/* ============================ LAYER 1 : ML-KEM ============================ */
typedef struct {
    MlKemKey key;
    WC_RNG   rng;
    byte     ct[WC_ML_KEM_1024_CIPHER_TEXT_SIZE];
    byte     ss[WC_ML_KEM_SS_SZ];
    int      lid;    /* remembered level id, for per-round reset */
    int      phase;  /* remembered phase (0 keygen /1 encaps /2 decaps), for reset */
    long     seed_idx; /* pre-shared seed index of this round's key (encaps/decaps) */
} kem_ctx_t;
static kem_ctx_t g_kem;

/* LAYER 1 TIMING POLICY: we do NOT mask interrupts across the measured region.
 * An earlier version wrapped each op in irq_lock()/irq_unlock() to keep the scheduler
 * tick out of the timed region, but masking IRQs for a whole ~5-13 ms crypto op, over
 * thousands of ops (5 rounds x 1000 iters), starves the USB-CDC serial and eventually
 * wedges the board (hang with no output). The tick ISR is ~1-2 us once per ms, so its
 * effect on a multi-ms op is ~0.1% AND it is consistent across all boards, so it does
 * not bias the cross-platform comparison. Correctness > a sub-0.1% jitter we cannot even
 * afford to chase. (Layer 2 likewise does not mask -- a handshake needs the net stack.)
 * The hardware cycle counter keeps running regardless of IRQ state, so timing accuracy
 * is unaffected by removing the lock. */
static int op_keygen(void *vp, uint64_t *ns)
{
    kem_ctx_t *c = vp;
    op_clk_t clk = clk_start();
    int r = wc_MlKemKey_MakeKey(&c->key, &c->rng);
    uint64_t el = clk_elapsed_ns(clk);
    if (el == 0ull) return -2;            /* discard: op >= 25 s (distinct from crypto-fail -1) */
    *ns = el; return r == 0 ? 0 : -1;
}
static int op_encaps(void *vp, uint64_t *ns)
{
    kem_ctx_t *c = vp;
    op_clk_t clk = clk_start();
    int r = wc_MlKemKey_Encapsulate(&c->key, c->ct, c->ss, &c->rng);
    uint64_t el = clk_elapsed_ns(clk);
    if (el == 0ull) return -2;            /* discard: op >= 25 s (distinct from crypto-fail -1) */
    *ns = el; return r == 0 ? 0 : -1;
}
static int op_decaps(void *vp, uint64_t *ns)
{
    kem_ctx_t *c = vp;
    /* CipherTextSize in wolfSSL 5.9.2 writes the length via a pointer and returns an
     * error code (it does NOT return the size). Fetch it OUTSIDE the timed region. */
    word32 ctlen = 0;
    if (wc_MlKemKey_CipherTextSize(&c->key, &ctlen) != 0) return -1;
    op_clk_t clk = clk_start();
    int r = wc_MlKemKey_Decapsulate(&c->key, c->ss, c->ct, ctlen);
    uint64_t el = clk_elapsed_ns(clk);
    if (el == 0ull) return -2;            /* discard: op >= 25 s (distinct from crypto-fail -1) */
    *ns = el; return r == 0 ? 0 : -1;
}

static int level_id(int lvl)
{
    return lvl == 512 ? WC_ML_KEM_512 : lvl == 768 ? WC_ML_KEM_768
         : lvl == 1024 ? WC_ML_KEM_1024 : -1;
}

/* PRE-SHARED SEEDS (decided 2026-11-06). ML-KEM encaps/decaps cost depends on the KEY: matrix A
 * is rejection-sampled from the public seed rho, and some keys need an extra SHAKE-128 squeeze
 * (~17-20 k cycles, seen as one shifted round in sweep v2). With one random key per round, each
 * board measured its own 3 random keys. Now round r's key -- and for decaps its ciphertext --
 * come from a FIXED seed r, identical on every board, so every board does bit-identical work.
 *   key seed (d||z, 64 B, FIPS 203) = SHA-256("PQCB"|'K'|level|r|0) || SHA-256("PQCB"|'K'|level|r|1)
 *   decaps ct message m (32 B)      = SHA-256("PQCB"|'M'|level|r|0)
 *   (level = 512/768/1024 as 2 bytes big-endian, r = 4 bytes big-endian, block = 1 byte)
 * MakeKeyWithRandom/EncapsulateWithRandom are exactly what MakeKey/Encapsulate call after drawing
 * those bytes from the RNG, so the resulting key is an ordinary ML-KEM key. All of this is SETUP,
 * outside the timed region; the timed ops are unchanged (keygen still draws fresh randomness each
 * iteration, encaps still draws a fresh m each iteration). */
static int kem_level_bits(int lid)
{
    return lid == WC_ML_KEM_512 ? 512 : lid == WC_ML_KEM_768 ? 768 : 1024;
}
static int kem_seed_bytes(byte *out, int len, int lid, long idx, char kind)
{
    byte in[12], h[WC_SHA256_DIGEST_SIZE];
    int lv = kem_level_bits(lid);
    for (int blk = 0; blk * WC_SHA256_DIGEST_SIZE < len; blk++) {
        in[0] = 'P'; in[1] = 'Q'; in[2] = 'C'; in[3] = 'B'; in[4] = (byte)kind;
        in[5] = (byte)(lv >> 8); in[6] = (byte)lv;
        in[7] = (byte)(idx >> 24); in[8] = (byte)(idx >> 16); in[9] = (byte)(idx >> 8);
        in[10] = (byte)idx; in[11] = (byte)blk;
        if (wc_Sha256Hash(in, sizeof in, h) != 0) return -1;
        int n = len - blk * WC_SHA256_DIGEST_SIZE;
        if (n > WC_SHA256_DIGEST_SIZE) n = WC_SHA256_DIGEST_SIZE;
        memcpy(out + blk * WC_SHA256_DIGEST_SIZE, h, n);
    }
    return 0;
}

static int kem_setup(kem_ctx_t *c, int lid, int phase, long seed_idx)
{
    memset(c, 0, sizeof *c);
    c->lid = lid; c->phase = phase;          /* remember for per-round reset */
    c->seed_idx = seed_idx;
    if (wc_InitRng(&c->rng) != 0) return -1;
    if (wc_MlKemKey_Init(&c->key, lid, NULL, INVALID_DEVID) != 0) return -1;
    if (phase != 0) {                        /* encaps/decaps need a key: from seed r */
        byte d_z[64];
        if (kem_seed_bytes(d_z, sizeof d_z, lid, seed_idx, 'K') != 0) return -1;
        if (wc_MlKemKey_MakeKeyWithRandom(&c->key, d_z, sizeof d_z) != 0) return -1;
    }
    if (phase == 2) {                        /* decaps needs a ct: from seed r */
        byte m[32];
        if (kem_seed_bytes(m, sizeof m, lid, seed_idx, 'M') != 0) return -1;
        if (wc_MlKemKey_EncapsulateWithRandom(&c->key, c->ct, c->ss, m, sizeof m) != 0) return -1;
    }
    return 0;
}

/* First 8 bytes of SHA-256(public key [|| ciphertext for decaps]) -- printed per round so the
 * sweep log proves every board used the SAME key/ct for round r. */
static void kem_emit_fp(kem_ctx_t *c, long round_idx)
{
    static byte buf[WC_ML_KEM_1024_PUBLIC_KEY_SIZE + WC_ML_KEM_1024_CIPHER_TEXT_SIZE];
    byte h[WC_SHA256_DIGEST_SIZE];
    word32 pkl = 0, ctl = 0;
    if (c->phase == 0) return;               /* keygen: a fresh random key every iteration */
    if (wc_MlKemKey_PublicKeySize(&c->key, &pkl) != 0 ||
        wc_MlKemKey_EncodePublicKey(&c->key, buf, pkl) != 0) { MCU_EMIT("KEYFP round=%ld fp=ERR", round_idx); return; }
    if (c->phase == 2) {
        if (wc_MlKemKey_CipherTextSize(&c->key, &ctl) != 0) ctl = 0;
        memcpy(buf + pkl, c->ct, ctl);
    }
    if (wc_Sha256Hash(buf, pkl + ctl, h) != 0) { MCU_EMIT("KEYFP round=%ld fp=ERR", round_idx); return; }
    MCU_EMIT("KEYFP round=%ld seed=%ld fp=%02x%02x%02x%02x%02x%02x%02x%02x", round_idx, c->seed_idx,
             h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7]);
}

/* Per-round reset: fully Free the ML-KEM key and RNG and re-create them, so any internal
 * per-call buffer allocation wolfCrypt does cannot accumulate across rounds. Called before
 * each round (outside the timed region). Keeps the SAME lid/phase, and re-establishes the
 * key/ciphertext that encaps/decaps need. This is what stops the ~5000-op heap exhaustion
 * hang: each round starts from a clean key, capping accumulation at one round's worth
 * (which we verified runs fine: 1000 iters x 1 round completes). */
static int kem_reset(void *vp)
{
    kem_ctx_t *c = vp;
    int lid = c->lid, phase = c->phase;
    long next = c->seed_idx + 1;             /* next round -> next pre-shared seed */
    wc_MlKemKey_Free(&c->key);
    wc_FreeRng(&c->rng);
    return kem_setup(c, lid, phase, next);    /* re-init (also re-stores lid/phase/seed) */
}

/* ---- mem mode: peak stack high-water of ONE op, measured on a dedicated painted
 * thread stack (mirrors the Pi harness measure_core.h). We run one op on a separate
 * thread whose stack Zephyr paints, then read the high-water via k_thread_stack_space_get
 * (unused bytes) -> used = size - unused. Baseline = a no-op thread's used stack; the net
 * is the op's own stack cost. Requires CONFIG_INIT_STACKS + CONFIG_THREAD_STACK_INFO.
 *
 * IMPORTANT: this MCU build uses WOLFSSL_SMALL_STACK, which deliberately moves wolfCrypt's
 * large working buffers OFF the stack and onto the HEAP. So stack high-water alone would
 * badly UNDER-report the true working memory. To capture the heap portion we also install
 * wolfCrypt allocator hooks (wolfSSL_SetAllocators) that track live allocated bytes and
 * record the PEAK reached during a single op. Total working memory = stack + heap peak. */
static volatile size_t g_heap_live = 0, g_heap_peak = 0;
/* wolfCrypt malloc/free/realloc hooks: prepend an 8-byte size header so free/realloc can
 * account correctly, and track live/peak bytes. Uses libc malloc underneath. */
static void *mem_malloc_hook(size_t n)
{
    size_t *p = (size_t*)malloc(n + sizeof(size_t));
    if (!p) return NULL;
    p[0] = n;
    g_heap_live += n;
    if (g_heap_live > g_heap_peak) g_heap_peak = g_heap_live;
    return (void*)(p + 1);
}
static void mem_free_hook(void *ptr)
{
    if (!ptr) return;
    size_t *p = (size_t*)ptr - 1;
    g_heap_live -= p[0];
    free(p);
}
static void *mem_realloc_hook(void *ptr, size_t n)
{
    if (!ptr) return mem_malloc_hook(n);
    size_t *op = (size_t*)ptr - 1; size_t old = op[0];
    size_t *np = (size_t*)realloc(op, n + sizeof(size_t));
    if (!np) return NULL;
    np[0] = n;
    g_heap_live += (n - old);
    if (g_heap_live > g_heap_peak) g_heap_peak = g_heap_live;
    return (void*)(np + 1);
}

#define MEM_PROBE_STACK 16384
K_THREAD_STACK_DEFINE(g_mem_probe_stack, MEM_PROBE_STACK);
static struct k_thread g_mem_probe_thread;
static mcu_op_fn g_mem_op; static void *g_mem_ctx; static volatile int g_mem_is_noop;

static void mem_probe_entry(void *a, void *b, void *c)
{
    (void)a;(void)b;(void)c;
    if (!g_mem_is_noop) { uint64_t t; g_mem_op(g_mem_ctx, &t); }
}
static size_t mem_probe_used(int noop)
{
    g_mem_is_noop = noop;
    k_tid_t tid = k_thread_create(&g_mem_probe_thread, g_mem_probe_stack, MEM_PROBE_STACK,
                                  mem_probe_entry, NULL, NULL, NULL,
                                  K_PRIO_PREEMPT(0), 0, K_NO_WAIT);
    k_thread_join(tid, K_FOREVER);
    size_t unused = 0;
    (void)k_thread_stack_space_get(&g_mem_probe_thread, &unused);
    return (size_t)MEM_PROBE_STACK - unused;   /* bytes actually used (high-water) */
}

static void do_layer1_mem(int phase, int lid, int lvl, long rounds)
{
    const char *pn = phase == 0 ? "keygen" : phase == 1 ? "encaps" : "decaps";
    char label[32]; snprintf(label, sizeof label, "mlkem%d_%s", lvl, pn);
    if (kem_setup(&g_kem, lid, phase, 0) != 0) { MCU_EMIT("ERR kem setup failed"); return; }
    mcu_op_fn op = phase == 0 ? op_keygen : phase == 1 ? op_encaps : op_decaps;
    g_mem_op = op; g_mem_ctx = &g_kem;

    /* install heap-tracking allocators for the duration of the mem measurement */
    wolfSSL_Malloc_cb  oldm; wolfSSL_Free_cb oldf; wolfSSL_Realloc_cb oldr;
    (void)wolfSSL_GetAllocators(&oldm, &oldf, &oldr);
    (void)wolfSSL_SetAllocators(mem_malloc_hook, mem_free_hook, mem_realloc_hook);

    double s_sum=0, s_sq=0, h_sum=0, h_sq=0; long nr=0;
    for (long r=0;r<rounds;r++){
        size_t base = mem_probe_used(1);                 /* no-op thread stack baseline */
        g_heap_live = 0; g_heap_peak = 0;                /* reset heap peak for this op */
        size_t peak = mem_probe_used(0);                 /* one real op */
        double stack_kb = (peak > base ? (double)(peak - base) : 0.0) / 1024.0;
        double heap_kb  = (double)g_heap_peak / 1024.0;
        double total_kb = stack_kb + heap_kb;
        MCU_EMIT("ROUND %ld group=%s phase=%s mode=mem net_op_stack_KB=%.2f heap_peak_KB=%.2f working_KB=%.2f",
                 r, label, pn, stack_kb, heap_kb, total_kb);
        s_sum+=stack_kb; s_sq+=stack_kb*stack_kb;
        h_sum+=heap_kb;  h_sq+=heap_kb*heap_kb; nr++;
    }
    /* restore the normal allocators */
    (void)wolfSSL_SetAllocators(oldm, oldf, oldr);

    double s_mean = nr? s_sum/nr:0, s_sd = nr>1? sqrt((s_sq-nr*s_mean*s_mean)/(nr-1)):0;
    double h_mean = nr? h_sum/nr:0, h_sd = nr>1? sqrt((h_sq-nr*h_mean*h_mean)/(nr-1)):0;
    MCU_EMIT("AGG group=%s rounds=%ld mode=mem net_op_stack_KB=%.2f stack_sd=%.2f heap_peak_KB=%.2f heap_sd=%.2f working_KB=%.2f",
             label, rounds, s_mean, s_sd, h_mean, h_sd, s_mean+h_mean);

    /* static sizes (bytes): public key, secret key, ciphertext, shared secret */
    word32 pk=0, sk=0, ct=0, ss=0;
    (void)wc_MlKemKey_PublicKeySize(&g_kem.key, &pk);
    (void)wc_MlKemKey_PrivateKeySize(&g_kem.key, &sk);
    (void)wc_MlKemKey_CipherTextSize(&g_kem.key, &ct);
    (void)wc_MlKemKey_SharedSecretSize(&g_kem.key, &ss);
    MCU_EMIT("SIZES lib=wolfssl level=%d pk=%u sk=%u ct=%u ss=%u",
             lvl, (unsigned)pk, (unsigned)sk, (unsigned)ct, (unsigned)ss);

    wc_MlKemKey_Free(&g_kem.key); wc_FreeRng(&g_kem.rng);
}

static void do_layer1(int phase, int lvl, int mode, long count, long rounds, long warmup)
{
    int lid = level_id(lvl);
    if (lid < 0) { MCU_EMIT("ERR bad level %d", lvl); return; }
    if (mode == 2) { do_layer1_mem(phase, lid, lvl, rounds); return; }   /* mem mode */
    if (count > MAX_SAMPLES) count = MAX_SAMPLES;
    if (kem_setup(&g_kem, lid, phase, 0) != 0) { MCU_EMIT("ERR kem setup failed"); return; }

    mcu_op_fn op   = phase == 0 ? op_keygen : phase == 1 ? op_encaps : op_decaps;
    const char *pn = phase == 0 ? "keygen"  : phase == 1 ? "encaps"  : "decaps";
    char label[32]; snprintf(label, sizeof label, "mlkem%d_%s", lvl, pn);

    if (mode == 1) mcu_run_time(label, 0, count, warmup, op, &g_kem);
    else           mcu_run(label, 0, count, rounds, warmup, op, &g_kem, g_scratch, kem_reset);

    wc_MlKemKey_Free(&g_kem.key); wc_FreeRng(&g_kem.rng);
}

/* Layer 1, ONE round only (orchestrator-driven "design b"): sets up a fresh context,
 * runs a single round of `count` ops with `warmup` warmup ops, emits the ROUND summary +
 * the RAW sample dump (for true-stats + integrity on the PC), then tears down. The caller
 * issues this once per round (passing the round index), validates the raw dump, and retries
 * that round if an integrity check fails. */
static void do_layer1_oneround(int phase, int lvl, long round_idx, long count, long warmup)
{
    int lid = level_id(lvl);
    if (lid < 0) { MCU_EMIT("ERR bad level %d", lvl); return; }
    if (count > MAX_SAMPLES) count = MAX_SAMPLES;
    /* round r uses pre-shared seed r (identical on every board) */
    if (kem_setup(&g_kem, lid, phase, round_idx) != 0) { MCU_EMIT("ERR kem setup failed"); return; }
    kem_emit_fp(&g_kem, round_idx);
    mcu_op_fn op   = phase == 0 ? op_keygen : phase == 1 ? op_encaps : op_decaps;
    const char *pn = phase == 0 ? "keygen"  : phase == 1 ? "encaps"  : "decaps";
    char label[32]; snprintf(label, sizeof label, "mlkem%d_%s", lvl, pn);
    /* reset=NULL: kem_setup already gave a fresh context for this single round */
    mcu_run_one_round(label, 0, round_idx, count, warmup, op, &g_kem, g_scratch, NULL);
    wc_MlKemKey_Free(&g_kem.key); wc_FreeRng(&g_kem.rng);
}

/* ====================== LAYER 1 : CLASSICAL KEX (ECDH) ======================
 * The classical baseline primitives TLS 1.3 actually uses -- all EPHEMERAL (ECDHE).
 * Layer 1 now characterises EVERY key-exchange primitive, ML-KEM AND classical, so the
 * fair comparison is cross-MCU PER primitive (same operation, different silicon), NOT
 * "ML-KEM vs ECDH" (whose operation structures differ). Two phases per curve:
 *   keygen : generate an ephemeral keypair   (fixed-base scalar multiply)
 *   derive : compute the ECDH shared secret  (variable-base scalar multiply) against a
 *            peer public key generated ONCE at setup -> isolates the derive multiply.
 * Same dual-clock timing and the SAME runners (mcu_run_one_round / mem probe) as ML-KEM.
 * Convention parity with ML-KEM mem: heap_peak = TRANSIENT working heap of one op; the
 * persistent key storage is reported separately on the SIZES line. */

/* ---- x25519 (Curve25519): fixed-size key struct, no heap ---- */
typedef struct { curve25519_key own, peer; WC_RNG rng; } c25519_ctx_t;
static c25519_ctx_t g_c25519;

static int op_c25519_keygen(void *vp, uint64_t *ns)
{
    c25519_ctx_t *c = vp;
    op_clk_t clk = clk_start();
    int r = wc_curve25519_make_key(&c->rng, CURVE25519_KEYSIZE, &c->own);
    uint64_t el = clk_elapsed_ns(clk);
    if (el == 0ull) return -2;
    *ns = el; return r == 0 ? 0 : -1;
}
static int op_c25519_derive(void *vp, uint64_t *ns)
{
    c25519_ctx_t *c = vp;
    byte out[CURVE25519_KEYSIZE]; word32 olen = sizeof out;
    op_clk_t clk = clk_start();
    int r = wc_curve25519_shared_secret(&c->own, &c->peer, out, &olen);
    uint64_t el = clk_elapsed_ns(clk);
    if (el == 0ull) return -2;
    *ns = el; return r == 0 ? 0 : -1;
}
static int c25519_setup(c25519_ctx_t *c, int phase)   /* 0 keygen, 1 derive */
{
    memset(c, 0, sizeof *c);
    if (wc_InitRng(&c->rng) != 0) return -1;
    if (wc_curve25519_init(&c->own) != 0) return -1;
    if (wc_curve25519_init(&c->peer) != 0) return -1;
    /* own is pre-made (keygen op overwrites it each iter; derive needs a valid private) */
    if (wc_curve25519_make_key(&c->rng, CURVE25519_KEYSIZE, &c->own) != 0) return -1;
    if (phase == 1 && wc_curve25519_make_key(&c->rng, CURVE25519_KEYSIZE, &c->peer) != 0) return -1;
    return 0;
}
static void c25519_teardown(c25519_ctx_t *c)
{
    wc_curve25519_free(&c->own); wc_curve25519_free(&c->peer); wc_FreeRng(&c->rng);
}

/* ---- NIST P-256 / P-384 / P-521 (ECDHE) ---- */
typedef struct { ecc_key own, peer; WC_RNG rng; int curve_id; int keysize; } ecc_ctx_t;
static ecc_ctx_t g_ecc;

/* keygen op: plain make_key onto the pre-made key object (same pattern as ML-KEM keygen --
 * make_key reuses the key's storage, so no per-op persistent allocation accumulates; a
 * fresh context per round via run1 caps anything internal, exactly as for ML-KEM). */
static int op_ecc_keygen(void *vp, uint64_t *ns)
{
    ecc_ctx_t *c = vp;
    op_clk_t clk = clk_start();
    int r = wc_ecc_make_key_ex(&c->rng, c->keysize, &c->own, c->curve_id);
    uint64_t el = clk_elapsed_ns(clk);
    if (el == 0ull) return -2;
    *ns = el; return r == 0 ? 0 : -1;
}
static int op_ecc_derive(void *vp, uint64_t *ns)
{
    ecc_ctx_t *c = vp;
    byte out[132]; word32 olen = sizeof out;   /* P-521 field = 66 B; generous headroom */
    op_clk_t clk = clk_start();
    int r = wc_ecc_shared_secret(&c->own, &c->peer, out, &olen);
    uint64_t el = clk_elapsed_ns(clk);
    if (el == 0ull) return -2;
    *ns = el; return r == 0 ? 0 : -1;
}
static int curve_params(const char *name, int *curve_id, int *keysize)
{
    if (!strcmp(name, "p256")) { *curve_id = ECC_SECP256R1; *keysize = 32; return 0; }
    if (!strcmp(name, "p384")) { *curve_id = ECC_SECP384R1; *keysize = 48; return 0; }
    if (!strcmp(name, "p521")) { *curve_id = ECC_SECP521R1; *keysize = 66; return 0; }
    return -1;
}
static int ecc_setup(ecc_ctx_t *c, int curve_id, int keysize, int phase)
{
    memset(c, 0, sizeof *c);
    c->curve_id = curve_id; c->keysize = keysize;
    if (wc_InitRng(&c->rng) != 0) return -1;
    if (wc_ecc_init(&c->own) != 0) return -1;
    if (wc_ecc_init(&c->peer) != 0) return -1;      /* init even for keygen so teardown is safe */
    if (wc_ecc_make_key_ex(&c->rng, keysize, &c->own, curve_id) != 0) return -1;  /* own pre-made */
#ifdef ECC_TIMING_RESISTANT
    (void)wc_ecc_set_rng(&c->own, &c->rng);         /* shared_secret needs an RNG when timing-resistant */
#endif
    if (phase == 1 && wc_ecc_make_key_ex(&c->rng, keysize, &c->peer, curve_id) != 0) return -1;
    return 0;
}
static void ecc_teardown(ecc_ctx_t *c)
{
    wc_ecc_free(&c->own); wc_ecc_free(&c->peer); wc_FreeRng(&c->rng);
}

/* ---- classical dispatch helpers ---- */
static int is_curve_name(const char *s)
{
    return !strcmp(s,"x25519") || !strcmp(s,"p256") || !strcmp(s,"p384") || !strcmp(s,"p521");
}
static int classical_phase_id(const char *p)   /* 0 keygen, 1 derive, -1 invalid */
{
    if (!strcmp(p,"keygen")) return 0;
    if (!strcmp(p,"derive")) return 1;
    return -1;
}
static int classical_setup(const char *curve, int phase)
{
    if (!strcmp(curve, "x25519")) return c25519_setup(&g_c25519, phase);
    int cid, ks;
    if (curve_params(curve, &cid, &ks) != 0) return -1;
    return ecc_setup(&g_ecc, cid, ks, phase);
}
static void classical_teardown(const char *curve)
{
    if (!strcmp(curve, "x25519")) c25519_teardown(&g_c25519);
    else                          ecc_teardown(&g_ecc);
}
static void classical_select(const char *curve, int phase,
                             mcu_op_fn *op, void **ctx, char *label, size_t ln)
{
    const char *pn = phase == 0 ? "keygen" : "derive";
    if (!strcmp(curve, "x25519")) {
        *op  = (phase == 0) ? op_c25519_keygen : op_c25519_derive;
        *ctx = &g_c25519;
    } else {
        *op  = (phase == 0) ? op_ecc_keygen : op_ecc_derive;
        *ctx = &g_ecc;
    }
    snprintf(label, ln, "%s_%s", curve, pn);
}
static void classical_sizes(const char *curve, unsigned *pk, unsigned *sk, unsigned *ss)
{
    if (!strcmp(curve, "x25519")) { *pk = 32; *sk = 32; *ss = 32; return; }
    int cid = 0, ks = 0; (void)curve_params(curve, &cid, &ks);
    *pk = (unsigned)(1 + 2*ks);   /* uncompressed X9.63 point */
    *sk = (unsigned)ks;
    *ss = (unsigned)ks;
}

/* Layer 1 classical, ONE round (streaming timing) -- parallels do_layer1_oneround. */
static void do_layer1_classical_oneround(const char *curve, int phase,
                                         long round_idx, long count, long warmup)
{
    if (count > MAX_SAMPLES) count = MAX_SAMPLES;
    if (classical_setup(curve, phase) != 0) { MCU_EMIT("ERR classical setup failed %s", curve); return; }
    mcu_op_fn op; void *ctx; char label[32];
    classical_select(curve, phase, &op, &ctx, label, sizeof label);
    mcu_run_one_round(label, 0, round_idx, count, warmup, op, ctx, g_scratch, NULL);
    classical_teardown(curve);
}

/* Layer 1 classical MEMORY -- parallels do_layer1_mem. The allocator hooks wrap the WHOLE
 * measurement (setup, ops, teardown) so ECC's internal free/realloc of setup-allocated
 * buffers can never mix allocators. Heap peak is a DELTA above the heap already live at op
 * start, so pre-existing (setup) allocations do not distort the per-op figure. */
static void do_layer1_classical_mem(const char *curve, int phase, long rounds)
{
    wolfSSL_Malloc_cb oldm; wolfSSL_Free_cb oldf; wolfSSL_Realloc_cb oldr;
    (void)wolfSSL_GetAllocators(&oldm, &oldf, &oldr);
    (void)wolfSSL_SetAllocators(mem_malloc_hook, mem_free_hook, mem_realloc_hook);

    if (classical_setup(curve, phase) != 0) {
        (void)wolfSSL_SetAllocators(oldm, oldf, oldr);
        MCU_EMIT("ERR classical setup failed %s", curve); return;
    }
    mcu_op_fn op; void *ctx; char label[32];
    classical_select(curve, phase, &op, &ctx, label, sizeof label);
    g_mem_op = op; g_mem_ctx = ctx;

    double s_sum=0, s_sq=0, h_sum=0, h_sq=0; long nr=0;
    for (long r=0;r<rounds;r++){
        size_t base  = mem_probe_used(1);          /* no-op thread stack baseline */
        size_t live0 = g_heap_live;                /* heap already live (setup) */
        g_heap_peak  = g_heap_live;                /* track the peak ABOVE the current level */
        size_t peak  = mem_probe_used(0);          /* one real op */
        double stack_kb = (peak > base ? (double)(peak - base) : 0.0) / 1024.0;
        double heap_kb  = (g_heap_peak > live0 ? (double)(g_heap_peak - live0) : 0.0) / 1024.0;
        double total_kb = stack_kb + heap_kb;
        MCU_EMIT("ROUND %ld group=%s phase=%s mode=mem net_op_stack_KB=%.2f heap_peak_KB=%.2f working_KB=%.2f",
                 r, label, (phase==0?"keygen":"derive"), stack_kb, heap_kb, total_kb);
        s_sum+=stack_kb; s_sq+=stack_kb*stack_kb; h_sum+=heap_kb; h_sq+=heap_kb*heap_kb; nr++;
    }

    double s_mean=nr?s_sum/nr:0, s_sd=nr>1?sqrt((s_sq-nr*s_mean*s_mean)/(nr-1)):0;
    double h_mean=nr?h_sum/nr:0, h_sd=nr>1?sqrt((h_sq-nr*h_mean*h_mean)/(nr-1)):0;
    MCU_EMIT("AGG group=%s rounds=%ld mode=mem net_op_stack_KB=%.2f stack_sd=%.2f heap_peak_KB=%.2f heap_sd=%.2f working_KB=%.2f",
             label, rounds, s_mean, s_sd, h_mean, h_sd, s_mean+h_mean);

    unsigned pk,sk,ss; classical_sizes(curve, &pk, &sk, &ss);
    MCU_EMIT("SIZES lib=wolfssl curve=%s pk=%u sk=%u ct=0 ss=%u", curve, pk, sk, ss);

    classical_teardown(curve);
    (void)wolfSSL_SetAllocators(oldm, oldf, oldr);   /* restore LAST, after teardown */
}

/* Layer 1 classical, mode dispatcher (mirrors do_layer1): 0 iters, 1 time, 2 mem. */
static void do_layer1_classical(const char *curve, int phase, int mode,
                                long count, long rounds, long warmup)
{
    if (mode == 2) { do_layer1_classical_mem(curve, phase, rounds); return; }
    if (count > MAX_SAMPLES) count = MAX_SAMPLES;
    if (classical_setup(curve, phase) != 0) { MCU_EMIT("ERR classical setup failed %s", curve); return; }
    mcu_op_fn op; void *ctx; char label[32];
    classical_select(curve, phase, &op, &ctx, label, sizeof label);
    if (mode == 1) mcu_run_time(label, 0, count, warmup, op, ctx);
    else           mcu_run(label, 0, count, rounds, warmup, op, ctx, g_scratch, NULL);
    classical_teardown(curve);
}

