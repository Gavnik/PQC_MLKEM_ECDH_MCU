static void ft_one(const char *k, const char *where, void (*fn)(uint32_t), uint32_t n, uint32_t per)
{
    uint32_t mn = 0xFFFFFFFFu, mx = 0;
    unsigned int key = irq_lock();
    fn(2);                                                 /* warm caches / prefetch */
    for (int i = 0; i < 7; i++) {
        uint32_t t0 = FT_DWT_CYCCNT;
        fn(n);
        uint32_t d = FT_DWT_CYCCNT - t0;
        if (d < mn) mn = d;
        if (d > mx) mx = d;
    }
    irq_unlock(key);
    uint32_t instr = n * per;
    MCU_EMIT("FETCHTEST kernel=%s where=%s fn=0x%08x instr=%u cyc_min=%u cyc_max=%u cpi_x1000=%u",
             k, where, (unsigned)(uintptr_t)fn, (unsigned)instr, (unsigned)mn, (unsigned)mx,
             (unsigned)((uint64_t)mn * 1000u / instr));
}

