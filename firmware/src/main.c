/* ============================ command console ============================ */
static void handle_line(char *ln)
{
    char *save = NULL, *tok = strtok_r(ln, " \t\r\n", &save);
    if (!tok) return;

    if (!strcmp(tok, "id")) {
        MCU_EMIT("ID board=%s arch=%s asm=%s placement=%s c25519=%s harden=%s kemkeys=seeded wx=%s opt=%s tmr_hz=%u rtos=zephyr lib=wolfssl",
                 BOARD_STR, ARCH_STR, ASM_STR, PLACEMENT_STR, C25519_STR, HARDEN_STR, wx_str(), OPT_STR,
                 (unsigned)sys_clock_hw_cycles_per_sec()); return;
    }
    if (!strcmp(tok, "arch")) { MCU_EMIT("ARCH %s", ARCH_STR); return; }
    if (!strcmp(tok, "clockcheck")) {
        /* Ground-truth the timebase against a real stopwatch. Every us_* figure is
         * cycle_count / CONFIG_SYS_CLOCK_HW_CYCLES_PER_SEC, so if that constant is not the
         * timer's true rate, every latency on this board is mis-scaled vs the other MCUs.
         * This spins until the cycle clock says 10.000 s and also reports the elapsed time
         * from the INDEPENDENT uptime/tick source. Read it against a phone stopwatch:
         *   - stopwatch ~10.0 s AND both clocks ~10 s  -> timebase correct, numbers trustworthy
         *   - stopwatch != 10.0 s                      -> SYS_CLOCK_HW_CYCLES_PER_SEC is wrong
         *                                                 by (real_seconds / 10) and every us_*
         *                                                 on this board must be rescaled
         *   - the two clocks disagree with EACH OTHER  -> tick vs cycle source mismatch */
        char *n = strtok_r(NULL, " \t\r\n", &save);
        uint64_t secs = n ? (uint64_t)strtoul(n, NULL, 10) : 10ULL;
        /* Waits by SLEEPING 1 ms at a time (not a busy spin) so USB-CDC keeps transmitting:
         * on Hazard3 the old busy spin held the START line in the USB buffer until the spin
         * ended, so a PC could not time it, and a long spin would hit the RP2350 no-yield
         * hang. The kernel cycle counter is the system timebase and keeps counting across
         * idle, so the measurement is unchanged. PC timing: clock_verify.py. */
        if (secs == 0 || secs > 120) secs = 10ULL;
        uint32_t up0 = k_uptime_get_32();
        uint64_t t0  = mcu_now_us();
        MCU_EMIT("CLOCKCHECK: START your stopwatch NOW -- spinning %llu s by the cycle clock "
                 "(assumed %u Hz)", (unsigned long long)secs,
                 (unsigned)CONFIG_SYS_CLOCK_HW_CYCLES_PER_SEC);
        while (mcu_now_us() - t0 < secs * 1000000ULL) { k_msleep(1); }
        uint64_t cyc_us = mcu_now_us() - t0;
        uint32_t up_ms  = k_uptime_get_32() - up0;
        MCU_EMIT("CLOCKCHECK: STOP stopwatch. cycle_clock=%llu us  uptime_clock=%u ms  "
                 "(both should read ~%llu s; compare to your stopwatch).",
                 (unsigned long long)cyc_us, (unsigned)up_ms, (unsigned long long)secs);
        return;
    }
    if (!strcmp(tok, "mpu")) {
        char *sub = strtok_r(NULL, " \t\r\n", &save);
        if (!sub)                 { dump_mpu(); return; }
        if (!strcmp(sub, "on"))   { mpu_enable_bg_only(); dump_mpu(); return; }
        if (!strcmp(sub, "off"))  { mpu_disable(); return; }
        if (!strcmp(sub, "wx")) {
            char *b = strtok_r(NULL, " \t\r\n", &save);
            char *s = strtok_r(NULL, " \t\r\n", &save);
            if (b && s) {
                mpu_set_wx((uint32_t)strtoul(b, NULL, 16), (uint32_t)strtoul(s, NULL, 16));
            } else if (!mpu_wx_auto()) {                 /* no args -> derive from linker symbols */
                MCU_EMIT("mpu wx: no reloc-region symbols; pass <base_hex> <size_hex>"); return;
            }
            dump_mpu(); return;
        }
        MCU_EMIT("usage: mpu | mpu on | mpu off | mpu wx [base_hex size_hex]");
        return;
    }
    if (!strcmp(tok, "faultw")) { fault_write_ro(); return; }   /* W^X proof: write RO code */
    if (!strcmp(tok, "faultx")) { fault_exec_xn();  return; }   /* W^X proof: exec from data */
    if (!strcmp(tok, "faultt")) { fault_write_tables(); return; } /* W^X proof: write RO tables */
    if (!strcmp(tok, "faultwend"))  { fault_write_ro_end(); return; }     /* last word of the code block   */
    if (!strcmp(tok, "faulttend"))  { fault_write_tables_end(); return; } /* last word of the tables block */
    if (!strcmp(tok, "faulttx"))    { fault_exec_tables(0); return; }     /* exec the tables (first word)  */
    if (!strcmp(tok, "faulttxend")) { fault_exec_tables(1); return; }     /* exec the tables (last word)   */
#if defined(CONFIG_PQC_FETCHTEST) && (defined(CONFIG_CPU_CORTEX_M33) || defined(CONFIG_CPU_CORTEX_M4))
    if (!strcmp(tok, "fetchtest"))  { fetch_test(); return; }             /* diagnostic image only */
#endif
#if defined(CONFIG_PQC_FETCHTEST) && defined(CONFIG_CPU_CORTEX_M4)
    if (!strcmp(tok, "memtopo"))    { memtopo_test(); return; }           /* diagnostic flash image only */
#endif
#if defined(CONFIG_RISCV)
    if (!strcmp(tok, "lastfault")) { rv_lastfault(); return; }   /* hz3: re-print the retained fault */
#endif
    if (!strcmp(tok, "nxtest")) { pmp_nx_read_test(); return; } /* RISC-V: does NX block reads? */
    if (!strcmp(tok, "pmpprobe")) { pmp_probe(); return; }       /* RISC-V: what A-modes + granularity? */
    if (!strcmp(tok, "net"))  { print_net(); return; }
    if (!strcmp(tok, "wifi")) {                 /* join WiFi (uses stored static creds) */
        char *t = strtok_r(NULL, " \t\r\n", &save);
        long to = t ? atol(t) : 30;             /* optional timeout seconds, default 30 */
        wifi_up(to); print_net(); return;
    }

    if (!strcmp(tok, "run")) {                       /* Layer 1 */
        char *ph = strtok_r(NULL, " \t\r\n", &save);
        char *lv = strtok_r(NULL, " \t\r\n", &save);
        char *md = strtok_r(NULL, " \t\r\n", &save);
        char *cn = strtok_r(NULL, " \t\r\n", &save);
        char *rd = strtok_r(NULL, " \t\r\n", &save);
        char *wu = strtok_r(NULL, " \t\r\n", &save);
        if (!ph || !lv || !md || !cn) { MCU_EMIT("ERR usage: run <phase> <level> <mode> <count> [rounds] [warmup]"); return; }
        if (is_curve_name(lv)) {                       /* classical ECDH curve (keygen|derive) */
            int cph = classical_phase_id(ph);
            if (cph < 0) { MCU_EMIT("ERR classical phase must be keygen|derive"); return; }
            long count = atol(cn), rounds = rd ? atol(rd) : 5, warmup = wu ? atol(wu) : 50;
            MCU_EMIT("BEGIN layer=1 phase=%s level=%s mode=%s count=%ld rounds=%ld warmup=%ld board=%s arch=%s",
                     ph, lv, md, count, rounds, warmup, BOARD_STR, ARCH_STR);
            do_layer1_classical(lv, cph, !strcmp(md,"time") ? 1 : !strcmp(md,"mem") ? 2 : 0, count, rounds, warmup);
            MCU_EMIT("END"); return;
        }
        int phase = !strcmp(ph,"keygen") ? 0 : !strcmp(ph,"encaps") ? 1 : !strcmp(ph,"decaps") ? 2 : -1;
        if (phase < 0) { MCU_EMIT("ERR bad phase %s", ph); return; }
        long count = atol(cn), rounds = rd ? atol(rd) : 5, warmup = wu ? atol(wu) : 50;
        MCU_EMIT("BEGIN layer=1 phase=%s level=%s mode=%s count=%ld rounds=%ld warmup=%ld board=%s arch=%s",
                 ph, lv, md, count, rounds, warmup, BOARD_STR, ARCH_STR);
        do_layer1(phase, atoi(lv), !strcmp(md,"time") ? 1 : !strcmp(md,"mem") ? 2 : 0, count, rounds, warmup);
        MCU_EMIT("END"); return;
    }

    if (!strcmp(tok, "run1")) {   /* Layer 1, ONE round (orchestrator-driven, streams raw) */
        char *ph = strtok_r(NULL, " \t\r\n", &save);
        char *lv = strtok_r(NULL, " \t\r\n", &save);
        char *ri = strtok_r(NULL, " \t\r\n", &save);   /* round index */
        char *cn = strtok_r(NULL, " \t\r\n", &save);   /* count */
        char *wu = strtok_r(NULL, " \t\r\n", &save);   /* warmup */
        if (!ph || !lv || !ri || !cn) { MCU_EMIT("ERR usage: run1 <phase> <level> <round_idx> <count> [warmup]"); return; }
        if (is_curve_name(lv)) {                       /* classical ECDH curve (keygen|derive) */
            int cph = classical_phase_id(ph);
            if (cph < 0) { MCU_EMIT("ERR classical phase must be keygen|derive"); return; }
            long ridx = atol(ri), count = atol(cn), warmup = wu ? atol(wu) : 50;
            MCU_EMIT("BEGIN1 layer=1 phase=%s level=%s round=%ld count=%ld warmup=%ld board=%s arch=%s",
                     ph, lv, ridx, count, warmup, BOARD_STR, ARCH_STR);
            do_layer1_classical_oneround(lv, cph, ridx, count, warmup);
            MCU_EMIT("END1 round=%ld", ridx); return;
        }
        int phase = !strcmp(ph,"keygen") ? 0 : !strcmp(ph,"encaps") ? 1 : !strcmp(ph,"decaps") ? 2 : -1;
        if (phase < 0) { MCU_EMIT("ERR bad phase %s", ph); return; }
        long ridx = atol(ri), count = atol(cn), warmup = wu ? atol(wu) : 50;
        MCU_EMIT("BEGIN1 layer=1 phase=%s level=%s round=%ld count=%ld warmup=%ld board=%s arch=%s",
                 ph, lv, ridx, count, warmup, BOARD_STR, ARCH_STR);
        do_layer1_oneround(phase, atoi(lv), ridx, count, warmup);
        MCU_EMIT("END1 round=%ld", ridx); return;
    }

    if (!strcmp(tok, "hs")) {                        /* Layer 2 */
        char *gp = strtok_r(NULL, " \t\r\n", &save);
        char *md = strtok_r(NULL, " \t\r\n", &save);
        char *cn = strtok_r(NULL, " \t\r\n", &save);
        char *rd = strtok_r(NULL, " \t\r\n", &save);
        char *wu = strtok_r(NULL, " \t\r\n", &save);
        if (!gp || !md || !cn) { MCU_EMIT("ERR usage: hs <group> <mode> <count> [rounds] [warmup]"); return; }
        long count = atol(cn), rounds = rd ? atol(rd) : 5, warmup = wu ? atol(wu) : 20;
        MCU_EMIT("BEGIN layer=2 group=%s mode=%s count=%ld rounds=%ld warmup=%ld board=%s arch=%s server=%s",
                 gp, md, count, rounds, warmup, BOARD_STR, ARCH_STR, PQC_SERVER_IP);
        do_layer2(gp, !strcmp(md,"time"), count, rounds, warmup);
        MCU_EMIT("END"); return;
    }

    MCU_EMIT("ERR unknown cmd");
}

/* ---- PSoC62 (Infineon CAT1A) polling console input ----------------------------------------
 * The PSoC62 hangs in console_getline_init() -> uart_register_input() -> console_input_init(),
 * whose FIFO-drain loop `while (uart_irq_rx_ready(dev)) uart_fifo_read(...)` spins forever on
 * this board: the CAT1 SCB UART keeps reporting RX-ready while uart_fifo_read consumes nothing
 * (its interrupt-driven RX API misbehaves under Zephyr's console subsys). That is exactly where
 * boot died -- "M1" printed, "M2" (after the init call) never did.
 *
 * The command-line INPUT path is independent of every measurement: Layer-1 timing uses the cycle
 * counter under irq_lock(), and commands are typed by a human. So we read lines by POLLING the
 * same console UART whose uart_poll_out() already prints the banner/printk reliably -- no RX IRQ,
 * no FIFO-drain loop, nothing to spin. The other three boards keep the validated interrupt-driven
 * console_getline() path untouched (see main()). Pure busy-poll, so it never relies on the system
 * tick or k_busy_wait (whose clock we have not confirmed firing on this board). */
#if defined(CONFIG_SOC_FAMILY_INFINEON_CAT1A)
static const struct device *g_psoc6_con;
static char g_psoc6_line[256];

static void psoc6_console_init(void)
{
    g_psoc6_con = DEVICE_DT_GET(DT_CHOSEN(zephyr_console));
    /* Intentionally NO uart_irq_rx_enable / uart_register_input: polling only. */
}

static char *psoc6_getline(void)
{
    size_t i = 0;
    for (;;) {
        unsigned char c;
        int rc = uart_poll_in(g_psoc6_con, &c);
        if (rc != 0) {                 /* -1 = no char ready; spin (human typing) */
            continue;
        }
        if (c == '\r' || c == '\n') {  /* end of line */
            if (i == 0) { continue; }  /* swallow empty lines and bare CR/LF pairs */
            g_psoc6_line[i] = '\0';
            printk("\r\n");            /* echo newline */
            return g_psoc6_line;
        }
        if (c == 0x08 || c == 0x7f) {  /* backspace / delete */
            if (i > 0) { i--; printk("\b \b"); }
            continue;
        }
        if (i < sizeof(g_psoc6_line) - 1) {
            g_psoc6_line[i++] = (char)c;
            printk("%c", c);           /* echo so the typist sees input */
        }
    }
}
#endif /* CONFIG_SOC_FAMILY_INFINEON_CAT1A */

int main(void)
{
    /* Forcibly disable the RP2350 HARDWARE watchdog by clearing the ENABLE bit directly
     * in its CTRL register. The evidence is conclusive that a ~free-running watchdog with
     * a timeout between 18 and 28 s is the cause:
     *     ML-KEM-512 x 5 rounds (~18 s wall-clock) COMPLETES.
     *     ML-KEM-768 x 5 rounds (~28 s wall-clock) HANGS -- same 5000 ops, same 5 rounds;
     *     the ONLY difference is elapsed time. 1000x4 (~22 s) works, 1000x5 (~28 s) dies.
     * The Zephyr wdt_disable() did NOT stop it (picotool 'load -x' reboots via the watchdog
     * and the boot path leaves it armed; the Zephyr driver doesn't clear it). So we clear
     * the hardware ENABLE bit ourselves.
     * RP2350 watchdog: base 0x400d8000, CTRL @ +0x00, bit 30 = ENABLE. */
    /* Guard on the RP2350 watchdog DT node (present only on the Pico builds, absent on
     * ESP32) so this register poke never compiles into a non-RP2350 target. */
#if DT_NODE_EXISTS(DT_NODELABEL(wdt0)) && (DT_REG_ADDR(DT_NODELABEL(wdt0)) == 0x400d8000)
    {
        volatile uint32_t *WDT_CTRL = (volatile uint32_t *)0x400d8000u;
        *WDT_CTRL &= ~(1u << 30);          /* clear ENABLE -> watchdog stopped (RP2350) */
    }
#endif

    /* If the console is on USB-CDC (the Pico builds), the USB device stack must be
     * brought up before the console works. usb_enable() is a no-op / absent on builds
     * without the USB device stack (e.g. ESP32 native serial), so guard on the Kconfig. */
#if defined(CONFIG_USB_DEVICE_STACK)
    /* usb_enable() is __deprecated in recent Zephyr (superseded by the USB-device-next stack),
     * but it is still functional and is what this CDC console build needs. Silence just this
     * one deprecation so it doesn't trip -Werror; the call itself is unchanged. */
    #pragma GCC diagnostic push
    #pragma GCC diagnostic ignored "-Wdeprecated-declarations"
    (void)usb_enable(NULL);
    #pragma GCC diagnostic pop
    /* give the host time to open the CDC port so the first lines aren't dropped */
    k_sleep(K_MSEC(1500));
#endif
    /* Console INPUT setup. PSoC62 uses a polling reader (psoc6_console_init / psoc6_getline);
     * every other board uses Zephyr's interrupt-driven console subsystem. See the psoc6 block
     * above for why the subsystem hangs on the CAT1 SCB UART. */
#if defined(CONFIG_SOC_FAMILY_INFINEON_CAT1A)
    psoc6_console_init();
#else
    console_getline_init();
#endif
    /* USB-CDC consoles (the Pico builds) need a moment for the host to open the CDC port or the
     * first line is dropped. A UART console (PSoC62 / KitProg3 bridge) and USB-serial-JTAG (ESP32)
     * do NOT need this -- and on a board whose system-tick interrupt isn't running, an unconditional
     * k_sleep() here blocks FOREVER (the timeout never fires), which is exactly what hung the PSoC62
     * after its boot banner. The Layer-1 benchmark times with the cycle counter + irq_lock (no tick),
     * so skipping this delay is safe; guard it to USB-CDC only. */
#if defined(CONFIG_USB_DEVICE_STACK)
    k_sleep(K_MSEC(2500));
#endif
    MCU_EMIT("READY board=%s arch=%s rtos=zephyr lib=wolfssl", BOARD_STR, ARCH_STR);

    /* Boot-time W^X on the two cores whose protection is our own code (the Arm cores get it from
     * Zephyr's MPU driver before main()). Applied once, before any benchmark command, so every
     * measurement of a CONFIG_PQC_WX=y image runs protected; wx= in SELFREPORT/ID says what is live. */
#if defined(CONFIG_RISCV) && defined(CONFIG_PQC_WX)
    int pmp_skip = pmp_skip_this_boot();      /* must run before fault_report_on_boot() consumes it */
#endif
    fault_report_on_boot();      /* print any W^X fault retained from a previous boot */
#if defined(CONFIG_RISCV) && defined(CONFIG_PQC_WX)
    if (pmp_skip) MCU_EMIT("WX(PMP): NOT applied on this boot (reporting the unexpected fault above); reset to re-arm");
    else          (void)pmp_wx_apply();
#elif defined(CONFIG_SOC_SERIES_ESP32S3) && defined(CONFIG_PQC_WX)
    (void)esp32_pms_apply();
#endif
    MCU_EMIT("SELFREPORT board=%s arch=%s asm=%s placement=%s c25519=%s harden=%s kemkeys=seeded wx=%s opt=%s tmr_hz=%u",
             BOARD_STR, ARCH_STR, ASM_STR, PLACEMENT_STR, C25519_STR, HARDEN_STR, wx_str(), OPT_STR,
             (unsigned)sys_clock_hw_cycles_per_sec());
    print_net();

    for (;;) {
#if defined(CONFIG_SOC_FAMILY_INFINEON_CAT1A)
        char *line = psoc6_getline();       /* polling reader (no console subsys) */
#else
        char *line = console_getline();     /* blocking, newline-terminated */
#endif
        if (line) handle_line(line);
    }
    return 0;
}
