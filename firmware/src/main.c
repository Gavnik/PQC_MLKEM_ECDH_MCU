/* Greedy power-of-2 tiler: cover [s,e) with aligned RO+X regions, indices idx..maxidx.
 * Returns the next free index, or -1 if it didn't fit in the budget. Assumes 32B-aligned bounds. */
static int mpu_tile_rox(int idx, int maxidx, uint32_t s, uint32_t e)
{
    while (s < e) {
        if (idx > maxidx) return -1;
        uint32_t al = (s != 0u) ? (uint32_t)__builtin_ctz(s) : 31u;          /* max alignment at s */
        uint32_t sp = 31u; while (sp && ((1u << sp) > (e - s))) sp--;        /* floor log2(span)   */
        uint32_t L  = (al < sp) ? al : sp;
        if (L < 5u) L = 5u;                                                  /* min region = 32 B  */
        mpu_region_p2(idx, s, L, RASR_AP_RO);                               /* RO + executable    */
        s += (1u << L);
        idx++;
    }
    return idx;
}

static void mpu_set_wx(uint32_t base, uint32_t size)
{
#if defined(CONFIG_ARM_MPU)   /* Zephyr's MPU driver owns the MPU in this build: never reprogram it by hand */
    MCU_EMIT("refused: CONFIG_ARM_MPU=y -- Zephyr's MPU driver owns the MPU (use 'mpu' to dump it)");
    (void)base; (void)size;
    return;
#endif
    uint32_t s = base & 0xFFFFFFE0u;
    uint32_t e = (base + size + 0x1Fu) & 0xFFFFFFE0u;
    for (int i = 0; i < 8; i++) mpu_region_off(i);
    /* Attempt FULL two-sided: region 0 = all SRAM RW+XN, crypto RO+X tiles in regions 1..7. */
    mpu_region_p2(0, SRAM_BASE_ADDR, SRAM_LOG2, RASR_AP_RW | RASR_XN);
    int used = mpu_tile_rox(1, 7, s, e);
    if (used >= 0) {
        mpu_enable_core();
        MCU_EMIT("MPU W^X (PMSAv7) FULL two-sided: crypto [0x%08x..0x%08x) RO+X in %d tile(s) + all-SRAM RW+XN",
                 (unsigned)s, (unsigned)e, used - 1);
        return;
    }
    /* Crypto needs > budget. Drop the SRAM-XN background (so any un-tiled crypto stays executable
     * under the default map) and tile crypto RO+X across all 8 regions = code-RO only. */
    for (int i = 0; i < 8; i++) mpu_region_off(i);
    used = mpu_tile_rox(0, 7, s, e);
    mpu_enable_core();
    if (used >= 0)
        MCU_EMIT("MPU W^X (PMSAv7) code-RO only: crypto [0x%08x..0x%08x) RO+X in %d tile(s); no region left for data-NX background",
                 (unsigned)s, (unsigned)e, used);
    else
        MCU_EMIT("MPU W^X (PMSAv7) PARTIAL: crypto [0x%08x..0x%08x) needs >8 tiles; tail unprotected -- align the relocated region to a power of two for full W^X",
                 (unsigned)s, (unsigned)e);
}

