/* ---- time source (portable across ARM / RISC-V / Xtensa) ----
 * k_cycle_get_64() is NOT backed on the ESP32-S3 (Xtensa) and returns 0 there, which
 * made every measured delta 0.0000. k_cycle_get_32() IS supported on all three targets.
 * We read the 32-bit hardware cycle counter and convert cycles->ns using the kernel's
 * configured cycle frequency. Deltas are computed on the raw 32-bit counter so natural
 * unsigned wraparound is handled correctly (b - a is valid mod 2^32); a single ML-KEM
 * op (slowest: hz3 P-521 derive ~0.4 s) is far shorter than the wrap period (>= 17.9 s at
 * 240 MHz), and the 64-bit uptime clock guards it, so one wrap at most is impossible to miss. The counter is hardware and keeps running under irq_lock(). */

/* cycles (possibly wrapped delta) -> nanoseconds, using the kernel cycle frequency */
static inline uint64_t cyc32_delta_to_ns(uint32_t a, uint32_t b)
{
    uint32_t d = b - a;                              /* unsigned wraparound-safe (ONE wrap) */
    return k_cyc_to_ns_floor64((uint64_t)d);
}

/* DUAL-CLOCK timing for a single operation.
 * Problem: the 32-bit cycle counter wraps every ~28 s. A single-op delta is correct for
 * exactly ONE wrap, but if an op stalls long enough to wrap TWICE the unsigned delta
 * silently UNDERCOUNTS (e.g. a 30 s stall reports as 1.4 s) -- and would slip under any
 * fixed ceiling, so a naive guard cannot catch it.
 * Fix: bracket the op with BOTH clocks:
 *   - fine  = 32-bit cycle counter  -> sub-microsecond resolution for normal short ops
 *   - coarse= k_uptime_get() (ms)   -> 64-bit, CANNOT wrap for ~292 My: the ground truth
 *             for magnitude.
 * If the coarse clock says the op took >= 1 s but the fine delta disagrees badly, a wrap
 * (or multi-wrap) happened: we return the coarse value (ms->ns) so it is never
 * undercounted, and the caller's ceiling then correctly discards the stalled sample.
 * For normal ops (few ms) the fine delta is used, giving full precision. */
/* DUAL-CLOCK timing for a single operation, with ONE clean threshold.
 * The 32-bit cycle counter (fine) gives sub-microsecond precision but wraps every
 * ~28.6 s; its unsigned delta is correct for ZERO or ONE wrap, but a stall long enough
 * to wrap TWICE would silently undercount. To make undercounting impossible, we bracket
 * every op with a second, wrap-proof clock:
 *   - fine   = k_cycle_get_32() delta  -> precise, used for all normal ops.
 *   - coarse = k_uptime_get() (ms)     -> 64-bit, cannot wrap (~292 My): TRUE magnitude.
 * Rule (T = 25000 ms, chosen BELOW the 28.6 s wrap point with a ~3.6 s safety margin):
 *   - coarse <  T : trust the precise fine value. (coarse < 25 s < 28.6 s guarantees the
 *                   fine counter wrapped ZERO times, so it cannot be undercounted.)
 *   - coarse >= T : the op is pathologically long (no real ML-KEM op or TLS handshake is
 *                   anywhere near 25 s) AND the fine clock is nearing its wrap cliff ->
 *                   DISCARD. Signalled by returning 0 (impossible for a real op), which
 *                   the op functions propagate as a failure so mcu_run drops+counts it.
 * A wrapped fine value can NEVER be trusted: wrapping needs >=28.6 s real -> coarse
 * >=28600 >= T -> always discarded on the coarse magnitude. */
#define PQC_OP_DISCARD_MS 25000ull
typedef struct { uint32_t c0; int64_t m0; } op_clk_t;
static inline op_clk_t clk_start(void){ op_clk_t s; s.m0=k_uptime_get(); s.c0=k_cycle_get_32(); return s; }
static inline uint64_t clk_elapsed_ns(op_clk_t s){
    uint32_t c1=k_cycle_get_32();
    int64_t  m1=k_uptime_get();
    uint64_t coarse_ms= (uint64_t)(m1 - s.m0);               /* 64-bit, cannot wrap */
    if (coarse_ms >= PQC_OP_DISCARD_MS) return 0ull;         /* sentinel -> discard */
    return cyc32_delta_to_ns(s.c0, c1);                      /* precise, guaranteed un-wrapped */
}

uint64_t mcu_now_us(void)
{
    /* HIGH-RESOLUTION monotonic microseconds for Layer 2 handshake timing.
     * Using k_uptime (1 ms tick) would quantize handshakes to whole milliseconds --
     * far too coarse for 7-25 ms handshakes. Instead we use the same hardware cycle
     * counter as Layer 1, but ACCUMULATE it into 64 bits so it never wraps even for a
     * handshake that stalls for many seconds:
     *   - k_cycle_get_32() is the only cycle API backed on all three targets (the 64-bit
     *     one returns 0 on the ESP32-S3).
     *   - We track the previous 32-bit reading; whenever the new reading is smaller, the
     *     counter wrapped, so we add 2^32 to a 64-bit accumulator.
     *   - Convert the full 64-bit cycle count to ns (per-platform frequency), then to us.
     * Must be called often enough that we never MISS a full wrap (~28.6 s at 150 MHz on
     * the Pico) -- Layer 2 samples every handshake (ms scale), so that is guaranteed. */
    static uint32_t last32 = 0;
    static uint64_t acc_hi = 0;          /* accumulated high bits (multiples of 2^32) */
    static bool inited = false;
    uint32_t now32 = k_cycle_get_32();
    if (!inited) { last32 = now32; inited = true; }
    if (now32 < last32) acc_hi += (uint64_t)1 << 32;   /* wrapped since last call */
    last32 = now32;
    uint64_t cyc64 = acc_hi + now32;
    return (uint64_t)(k_cyc_to_ns_floor64(cyc64) / 1000ull);
}
static inline uint32_t now_cyc(void) { return k_cycle_get_32(); }

