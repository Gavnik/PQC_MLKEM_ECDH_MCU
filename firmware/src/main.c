static void esp_exec_test(uint32_t kind, uintptr_t dram_addr, const char *name, const char *what)
{
#if defined(CONFIG_PQC_WX)
    uintptr_t tgt = esp_ibus_alias(dram_addr);
    MCU_EMIT("%s: calling into %s %p through its I-bus alias 0x%08x (IRAM0 area 3, no access) -- expect panic + PMS fetch violation",
             name, what, (void *)dram_addr, (unsigned)tgt);
    k_msleep(120);
    esp_pms_clear();
    g_esp_kind = kind; g_esp_target = (uint32_t)tgt; g_esp_armed = 1;
    volatile uintptr_t a = tgt;                            /* indirect call (see fault_exec_xn) */
    void (*fn)(void) = (void (*)(void))a;
    fn();                                                  /* <-- must be blocked */
    g_esp_armed = 0;
    MCU_EMIT("%s: RETURNED -- no-execute was NOT enforced (note this result)", name);
#else
    (void)kind; (void)dram_addr; (void)what;
    MCU_EMIT("%s: refused -- image built without CONFIG_PQC_WX", name);
#endif
}

static void fault_exec_xn(void)
{
    g_nx_buf[0] = 0x0d; g_nx_buf[1] = 0xf0;   /* xtensa 'ret.n' -- only runs if NX NOT enforced */
#if defined(CONFIG_PQC_WX)
    esp_exec_test(2, (uintptr_t)(void *)g_nx_buf, "FAULTX", "DRAM data buffer");
#else
    uintptr_t tgt = (uintptr_t)(void *)g_nx_buf;
    MCU_EMIT("FAULTX: calling into DRAM buffer %p (W^X off) -- expect panic...", (void *)g_nx_buf);
    k_msleep(120);
    /* Launder the target through a volatile so the compiler emits an INDIRECT call (callx)
     * instead of a direct windowed call: a direct call from flash .text to this
     * address is out of range and the Xtensa longcall relocation cannot encode it (link error). */
    volatile uintptr_t a = tgt;
    void (*fn)(void) = (void (*)(void))a;
    fn();                                      /* fetch from DRAM -> faults on any S3 */
    MCU_EMIT("FAULTX: RETURNED -- no-execute was NOT enforced (note this result)");
#endif
}

/* Store into a protected word: dropped (read-back == original) or EXCCAUSE 3. Saved/restored. */
static void esp_store_test(const char *name, uintptr_t addr, const char *what)
{
    volatile uint32_t *p = (volatile uint32_t *)addr;
    MCU_EMIT("%s: store 0xDEADBEEF -> %p (%s); expect BLOCKED or EXCCAUSE 3", name, (void *)p, what);
    k_msleep(120);
    unsigned int key = irq_lock();
    uint32_t orig = *p;
#if defined(CONFIG_PQC_WX)
    esp_pms_clear();
#endif
    *p = 0xDEADBEEFu;
    __asm__ volatile("memw" ::: "memory");
    uint32_t rb = *p;
#if defined(CONFIG_PQC_WX)
    struct esp_pms_v v;
    esp_pms_read(addr >= 0x40000000u, &v);                 /* IRAM addresses: IRAM0 monitor */
#endif
    *p = orig;
    __asm__ volatile("memw" ::: "memory");
    irq_unlock(key);
    if (rb == 0xDEADBEEFu) {
        MCU_EMIT("%s: write LANDED (readback 0x%08x) -- NOT protected (%s)", name, (unsigned)rb,
                 strcmp(g_wx_hand, "pms") ? "expected: W^X off" : "W^X NOT ENFORCED!");
        return;
    }
#if defined(CONFIG_PQC_WX)
    MCU_EMIT("%s: PMS %s monitor: intr=%u addr=%p wr=%u loadstore=%u byte_en=0x%x", name, addr >= 0x40000000u ? "IRAM0" : "DRAM0",
             (unsigned)v.intr, v.addr, (unsigned)v.wr, (unsigned)v.ls, (unsigned)v.byte_en);
    if (v.intr && v.wr && (addr >= 0x40000000u ? esp_pms_same(v.addr, (uint32_t)addr)
                                              : esp_pms_dram_hit(&v, (uint32_t)addr)))
        MCU_EMIT("%s: write BLOCKED (readback 0x%08x == orig) and recorded by the PMS at the target -- ENFORCED", name, (unsigned)rb);
    else
        MCU_EMIT("%s: UNEXPECTED -- the write did not land, but the PMS recorded no write violation at the target", name);
#else
    MCU_EMIT("%s: write did not land (readback 0x%08x) on an image without CONFIG_PQC_WX -- UNEXPECTED", name, (unsigned)rb);
#endif
}
static void fault_write_ro_end(void)
{
    uintptr_t s = (uintptr_t)_pqc_code_start, e = (uintptr_t)_pqc_code_end;
    if (!s || e <= s) { MCU_EMIT("FAULTWEND: n/a -- this build has no crypto code block (flash placement)"); return; }
    esp_store_test("FAULTWEND", (e - 4u) & ~(uintptr_t)3u, "LAST word of the crypto CODE block in IRAM, R+X");
}
static void fault_write_tables_end(void)
{
    uintptr_t s = (uintptr_t)_pqc_tables_start, e = (uintptr_t)_pqc_tables_end;
    if (!s || e <= s) { MCU_EMIT("FAULTTEND: n/a -- this build has no tables block (flash placement)"); return; }
    esp_store_test("FAULTTEND", (e - 4u) & ~(uintptr_t)3u, "LAST word of the crypto TABLES block in DRAM, R only");
}
/* faulttx / faulttxend: call into the first / last word of the tables block through its I-bus
 * alias. The PMS must block the fetch (verdict from the monitor, in the fatal handler). Refused
 * without the PMS (it would run table bytes). */
static void fault_exec_tables(int end)
{
    const char *name = end ? "FAULTTXEND" : "FAULTTX";
    uintptr_t s = (uintptr_t)_pqc_tables_start, e = (uintptr_t)_pqc_tables_end;
    if (!s || e <= s) { MCU_EMIT("%s: n/a -- this build has no tables block (flash placement)", name); return; }
    if (strcmp(g_wx_hand, "pms")) { MCU_EMIT("%s: refused -- W^X is off, the call would execute table bytes", name); return; }
    esp_exec_test(4, end ? ((e - 4u) & ~(uintptr_t)3u) : s, name, "the crypto TABLES block");
}

/* faultw: store into IRAM code (hybrid: the crypto code block; flash: Zephyr's own IRAM code).
 * faultt: store into the crypto TABLES block in DRAM (DRAM0 area 2, R only).
 * Both: dropped by the PMS (read-back = original) AND recorded by its monitor. The original word
 * is saved and restored under irq_lock either way, so live code is never corrupted. */
static void fault_write_ro(void)
{
    uintptr_t p = (uintptr_t)(void *)(_pqc_code_start ? _pqc_code_start : _iram_text_start);
    if (!p) { MCU_EMIT("FAULTW: _iram_text_start symbol absent -- cannot target IRAM"); return; }
    esp_store_test("FAULTW", p, _pqc_code_start ? "crypto CODE block in IRAM, R+X" : "IRAM code, R+X");
}

